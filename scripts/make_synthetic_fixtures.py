"""Write the synthetic Hidroweb series S1-S8 (research R-06); see contracts/update-golden-cli.md.

A fixed seed per series and integer tenths of a millimetre. The layout copies the real exports
in src/csv/: ISO-8859-1, CRLF, 12 lines before the column header, `;` separator with a trailing
`;` on data rows, `,` decimal mark, level 1 (raw) rows before level 2 (consisted) rows, newest
month first. The CSVs are generated once and committed; the committed bytes are the fixtures.
"""
import argparse
import calendar
import math
import random
import sys
from pathlib import Path

SEED = 1001

HEADER_LINES = [
    "Synthetic series {series_id} - CalculoIDF test fixture (spec 001)",
    "Generated by scripts/make_synthetic_fixtures.py; not ANA data",
    "Station code {station} is arbitrary and identifies no real station",
    "",
    "NivelConsistencia: 1 = Bruto, 2 = Consistido",
    "TipoMedicaoChuvas: 1 = Pluviômetro, 2 = Pluviógrafo, 3 = Data logger",
    "Status: 0 = Branco, 1 = Real, 2 = Estimado, 3 = Duvidoso, 4 = Acumulado",
    "",
    "Restrições da consulta:",
    "Código da Estação:{station}",
    "",
    "",
]

COLUMNS = (
    ["EstacaoCodigo", "NivelConsistencia", "Data", "TipoMedicaoChuvas", "Maxima", "Total",
     "DiaMaxima", "NumDiasDeChuva", "MaximaStatus", "TotalStatus", "NumDiasDeChuvaStatus",
     "TotalAnual", "TotalAnualStatus"]
    + [f"Chuva{day:02d}" for day in range(1, 32)]
    + [f"Chuva{day:02d}Status" for day in range(1, 32)]
)

# Probability of a rainy day per calendar month (wet season October-March).
WET_PROBABILITY = {1: 0.55, 2: 0.50, 3: 0.45, 4: 0.25, 5: 0.15, 6: 0.10,
                   7: 0.08, 8: 0.08, 9: 0.20, 10: 0.35, 11: 0.45, 12: 0.55}
MEAN_WET_DAY_TENTHS = 120

def water_year(year):
    return {(year, m) for m in (10, 11, 12)} | {(year + 1, m) for m in range(1, 10)}


S4_EMPTY_YEAR = water_year(1985)

CASES = [
    {"id": "S1", "station": 9999001, "consisted": ((2000, 1), (2008, 6)),
     "raw": ((2000, 1), (2008, 6))},
    {"id": "S2", "station": 9999002, "consisted": ((1980, 1), (2000, 6)),
     "raw": ((1980, 1), (2000, 6))},
    {"id": "S3", "station": 9999003, "consisted": None,
     "raw": ((1960, 1), (1995, 6))},
    {"id": "S4", "station": 9999004, "consisted": ((1970, 1), (2005, 6)),
     "raw": ((1970, 1), (2005, 6)),
     "empty_consisted": S4_EMPTY_YEAR, "empty_raw": S4_EMPTY_YEAR},
    {"id": "S5", "station": 9999005, "consisted": ((1980, 10), (2002, 3)),
     "raw": ((1980, 10), (2002, 3))},
    {"id": "S6", "station": 9999006, "consisted": ((1980, 3), (2001, 9)),
     "raw": ((1980, 3), (2001, 9))},
    {"id": "S7", "station": 9999007, "consisted": ((1990, 10), (2000, 9)),
     "raw": ((1990, 10), (2000, 9))},
    # Water year 1966 is empty in the consisted level and precedes the first raw month
    # (Mar/1968), so Maxima is NaN at the fillna(0, inplace=True) of
    # process_data.merge_and_fill_data (D-13). A single month would not show it: the per-year
    # maximum skips NaN (research R-06).
    {"id": "S8", "station": 9999008, "consisted": ((1965, 1), (2000, 6)),
     "raw": ((1968, 3), (2000, 6)), "empty_consisted": water_year(1966)},
]


def months(first, last):
    year, month = first
    while (year, month) <= last:
        yield year, month
        year, month = (year + 1, 1) if month == 12 else (year, month + 1)


def daily_series(rng, first, last):
    """Return {(year, month): [tenths of mm per day]} for every month in the span."""
    series = {}
    for year, month in months(first, last):
        days = calendar.monthrange(year, month)[1]
        values = []
        for _ in range(days):
            if rng.random() < WET_PROBABILITY[month]:
                values.append(max(1, round(-MEAN_WET_DAY_TENTHS * math.log(1.0 - rng.random()))))
            else:
                values.append(0)
        series[(year, month)] = values
    return series


def tenths(value):
    return f"{value // 10},{value % 10}"


def row(station, level, year, month, values):
    date = f"01/{month:02d}/{year}"
    if values is None:
        fields = [str(station), str(level), date, "1", "", "", "", "", "0", "0", "0", "", "0"]
        fields += [""] * 31 + ["0"] * 31
    else:
        maximum = max(values)
        fields = [str(station), str(level), date, "1", tenths(maximum), tenths(sum(values)),
                  str(values.index(maximum) + 1), str(sum(1 for v in values if v > 0)),
                  "1", "1", "1", "", "0"]
        missing = 31 - len(values)
        fields += [tenths(v) for v in values] + [""] * missing
        fields += ["1"] * len(values) + ["0"] * missing
    return ";".join(fields) + ";"


def build(case):
    spans = [span for span in (case["consisted"], case["raw"]) if span]
    first = min(span[0] for span in spans)
    last = max(span[1] for span in spans)
    rng = random.Random(SEED * 100 + int(case["id"][1:]))
    series = daily_series(rng, first, last)

    lines = [line.format(station=f"{case['station']:08d}", series_id=case["id"])
             for line in HEADER_LINES]
    lines.append(";".join(COLUMNS))
    for level, span, empty in ((1, case["raw"], case.get("empty_raw", set())),
                               (2, case["consisted"], case.get("empty_consisted", set()))):
        if span is None:
            continue
        for year, month in reversed(list(months(*span))):
            values = None if (year, month) in empty else series[(year, month)]
            lines.append(row(case["station"], level, year, month, values))
    return ("\r\n".join(lines) + "\r\n").encode("iso-8859-1")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, type=Path,
                        help="output directory (tests/fixtures/synthetic)")
    args = parser.parse_args(argv)

    args.out.mkdir(parents=True, exist_ok=True)
    for case in CASES:
        content = build(case)
        path = args.out / f"{case['id']}.csv"
        if path.exists() and path.read_bytes() != content:
            print(f"{path} exists with different content; not overwritten", file=sys.stderr)
            return 1
        path.write_bytes(content)
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
